import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const base = process.env.FASTWRITE_E2E_URL ?? 'http://127.0.0.1:3223';
const browser = await chromium.launch({ channel: process.env.FASTWRITE_E2E_CHANNEL ?? 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1500, height: 1050 } });
await context.addInitScript(() => { localStorage.setItem('fastwrite.completion.enabled', 'false'); localStorage.setItem('fastwrite.collaboration.enabled', 'false'); });
const page = await context.newPage(), errors = [];
page.on('pageerror', error => errors.push(error.stack));
const until = async (predicate, label) => { const end = Date.now() + 15000; while (!(await predicate())) { assert.ok(Date.now() < end, label); await page.waitForTimeout(40); } };
try {
  const project = await (await context.request.post(`${base}/api/projects`, { data: { name: 'Two checkpoint comparison' } })).json();
  const root = `${base}/api/projects/${project.id}`;
  const read = async () => (await (await context.request.get(`${root}/file?path=main.tex`)).json());
  const save = async content => { const file = await read(); assert.ok((await context.request.put(`${root}/file?path=main.tex`, { data: { content, baseVersion: file.file.version } })).ok()); };
  const checkpoint = async () => { assert.ok((await context.request.post(`${root}/history/checkpoint`)).ok()); return (await (await context.request.get(`${root}/history-page`)).json()).commits[0].oid; };
  const initial = await read();
  await save(`% FIRST_CHECKPOINT\n${initial.content}`);
  for (const [path, content] of [['old name.tex', 'unchanged rename content\n'.repeat(10)], ['deleted.tex', 'deleted content\n']]) assert.ok((await context.request.post(`${root}/files`, { data: { path, content } })).ok());
  const original = await checkpoint();
  await save(`% MIDDLE_CHECKPOINT\n${initial.content}`); await checkpoint();
  await save(`% LAST_CHECKPOINT\n${initial.content}`);
  assert.ok((await context.request.patch(`${root}/files`, { data: { from: 'old name.tex', to: '新 name.tex' } })).ok());
  assert.ok((await context.request.delete(`${root}/files?path=deleted.tex`)).ok());
  const modified = await checkpoint();
  await page.goto(`${base}/projects/${project.id}`);
  await page.getByRole('textbox', { name: 'Source editor for main.tex', exact: true }).waitFor();
  await page.getByRole('navigation', { name: 'Workspace views' }).getByRole('button', { name: 'Git', exact: true }).click();
  await page.getByLabel('Original checkpoint', { exact: true }).selectOption(original);
  await page.getByLabel('Modified checkpoint', { exact: true }).selectOption(modified);
  await page.getByRole('button', { name: 'Compare checkpoints', exact: true }).click();
  const files = page.getByRole('list', { name: 'Changes between selected checkpoints' });
  await files.waitFor();
  assert.match(await files.innerText(), /R.*old name.tex → 新 name.tex/s);
  assert.match(await files.innerText(), /D.*deleted.tex/s);
  await files.getByRole('button', { name: 'M main.tex', exact: true }).click();
  const activeDiff = () => page.locator('.diff-tab-panel:not([hidden]) .workspace-diff');
  const diffText = () => activeDiff().locator('.view-lines').allTextContents().then(lines => lines.join('\n'));
  await until(async () => { const text = await diffText(); return text.includes('FIRST_CHECKPOINT') && text.includes('LAST_CHECKPOINT'); }, 'selected OIDs determine both diff sides');
  assert.ok(!(await diffText()).includes('MIDDLE_CHECKPOINT'));
  const firstModel = await activeDiff().locator('.diff-editor-host').getAttribute('data-modified-model-id');
  await files.getByRole('button', { name: /R old name.tex → 新 name.tex/ }).click();
  await until(async () => (await diffText()).includes('unchanged'), 'renamed file uses its old path for original');
  assert.ok(!(await activeDiff().locator('.diff-identities').innerText()).includes('file does not exist'));
  const tablist = page.getByRole('tablist', { name: 'Open editors' });
  const firstTab = tablist.getByRole('tab', { name: `main.tex (${original.slice(0, 8)} → ${modified.slice(0, 8)})`, exact: true });
  assert.equal(await tablist.getByRole('tab').count(), 3, 'source and two comparison tabs coexist');
  await firstTab.click();
  assert.equal(await activeDiff().locator('.diff-editor-host').getAttribute('data-modified-model-id'), firstModel, 'switching diff tabs retains immutable model identity');
  await files.getByRole('button', { name: 'M main.tex', exact: true }).click();
  assert.equal(await tablist.getByRole('tab').count(), 3, 'opening the same comparison reuses its tab');
  await firstTab.click({ button: 'middle' });
  await until(async () => await tablist.getByRole('tab').count() === 2, 'middle click closes only one comparison');
  await page.getByRole('button', { name: 'Close comparison', exact: true }).click();
  await page.getByLabel('Original checkpoint', { exact: true }).selectOption(modified);
  await page.getByLabel('Modified checkpoint', { exact: true }).selectOption(original);
  await page.getByRole('button', { name: 'Compare checkpoints', exact: true }).click();
  await until(async () => (await files.innerText()).includes('新 name.tex → old name.tex'), 'reverse comparison reverses rename');
  assert.match(await files.innerText(), /A.*deleted.tex/s);
  await page.getByLabel('Original checkpoint', { exact: true }).selectOption(original);
  await page.getByRole('button', { name: 'Compare checkpoints', exact: true }).click();
  await page.getByText('No differences between these checkpoints.', { exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: 'pass', projectId: project.id, original, modified, cases: ['non-adjacent checkpoints', 'rename old path', 'reverse comparison', 'identical checkpoints', 'multiple diff tabs retain model identity', 'duplicate comparison reuses tab', 'middle click closes only target diff'] }));
} finally { await browser.close(); }
