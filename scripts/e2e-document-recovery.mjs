import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const base = process.env.FASTWRITE_E2E_URL ?? 'http://127.0.0.1:3221';
const browser = await chromium.launch({ channel: process.env.FASTWRITE_E2E_CHANNEL ?? 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1500, height: 1050 } });
await context.addInitScript(() => { localStorage.setItem('fastwrite.completion.enabled', 'false'); localStorage.setItem('fastwrite.collaboration.enabled', 'false'); });
const page = await context.newPage(), errors = [];
page.on('pageerror', error => errors.push(error.stack));
const until = async (predicate, label) => { const end = Date.now() + 20000; while (!(await predicate())) { assert.ok(Date.now() < end, label); await page.waitForTimeout(40); } };
const source = () => page.getByRole('textbox', { name: 'Source editor for main.tex', exact: true });
const dialog = () => page.getByRole('dialog', { name: 'Recover main.tex', exact: true });
const result = () => dialog().getByRole('textbox', { name: 'Recovery result', exact: true });
try {
  const create = async name => { const response = await context.request.post(`${base}/api/projects`, { data: { name } }); assert.ok(response.ok()); return response.json(); };
  const project = await create('Three-way recovery regression');
  const root = `${base}/api/projects/${project.id}`;
  const read = async (path = 'main.tex') => (await (await context.request.get(`${root}/file?path=${encodeURIComponent(path)}`)).json());
  const initial = await read();
  await page.goto(`${base}/projects/${project.id}`); await source().waitFor();
  const theirs = `% REMOTE_VERSION\n${initial.content}`;
  const remote = await context.request.put(`${root}/file?path=main.tex`, { data: { content: theirs, baseVersion: initial.file.version } }); assert.ok(remote.ok());
  await source().focus(); await page.keyboard.press('Control+Home'); await page.keyboard.insertText('% LOCAL_VERSION\n');
  await page.locator('.save-indicator--conflict').waitFor();
  assert.equal((await read()).content, theirs);
  await page.getByRole('button', { name: /Compare \/ recover/ }).click(); await result().waitFor();
  await dialog().getByRole('button', { name: 'Base vs local', exact: true }).click();
  await until(async () => (await dialog().locator('.view-lines').allTextContents()).join('\n').includes('LOCAL_VERSION'), 'base and local comparison rendered');
  await dialog().getByRole('button', { name: 'Server vs local', exact: true }).click();
  await until(async () => (await dialog().locator('.view-lines').allTextContents()).join('\n').includes('REMOTE_VERSION'), 'server and local comparison rendered');
  await dialog().getByRole('button', { name: 'Server vs editable result', exact: true }).click();
  const merged = `% LOCAL_VERSION\n${theirs}`;
  await result().focus(); await page.keyboard.press('Control+a'); await page.keyboard.insertText(merged);
  await page.keyboard.press('Control+s');
  await dialog().waitFor({ state: 'detached' });
  assert.equal((await read()).content, merged);
  await page.getByRole('button', { name: /Compare \/ recover/ }).click(); await result().waitFor();
  await dialog().getByLabel('Local version', { exact: true }).selectOption('working');
  await until(async () => await dialog().getByRole('button', { name: 'Use server text', exact: true }).isEnabled(), 'server baseline loaded');
  const next = await read(), newer = `% NEWER_REMOTE\n${next.content}`;
  assert.ok((await context.request.put(`${root}/file?path=main.tex`, { data: { content: newer, baseVersion: next.file.version } })).ok());
  await result().focus(); await page.keyboard.press('Control+Home'); await page.keyboard.insertText('% REVIEWED_RESULT\n');
  await dialog().getByRole('button', { name: 'Apply result and save', exact: true }).click();
  await dialog().getByRole('alert').filter({ hasText: /changed/ }).waitFor();
  assert.equal((await read()).content, newer, 'stale comparison never overwrites new server text');
  await dialog().getByLabel('Recovery copy path').fill('recovered.tex');
  await dialog().getByRole('button', { name: 'Save result as copy', exact: true }).click();
  await dialog().getByRole('status').filter({ hasText: 'Saved copy: recovered.tex' }).waitFor();
  assert.equal((await read('recovered.tex')).content, `% REVIEWED_RESULT\n${merged}`);
  assert.equal((await read()).content, newer);
  await dialog().getByRole('button', { name: 'Cancel', exact: true }).click(); await dialog().waitFor({ state: 'detached' });
  assert.match((await page.locator('.source-editor > .monaco-editor-host .view-lines').allTextContents()).join('\n'), /REVIEWED_RESULT/);

  const draftProject = await create('Delayed offline draft regression');
  const draftRoot = `${base}/api/projects/${draftProject.id}`;
  const draftBase = await (await context.request.get(`${draftRoot}/file?path=main.tex`)).json();
  const oldDraft = `% OLD_OFFLINE_DRAFT\n${draftBase.content}`;
  await page.evaluate(async ({ projectId, content, baseVersion, baseContent }) => {
    const db = await new Promise((resolve, reject) => { const request = indexedDB.open('fastwrite-offline-v1', 2); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error); });
    await new Promise((resolve, reject) => { const tx = db.transaction('drafts', 'readwrite'); tx.objectStore('drafts').put({ key: `${projectId}:main.tex`, content, baseVersion, baseContent, savedAt: Date.now() }); tx.oncomplete = resolve; tx.onerror = () => reject(tx.error); }); db.close();
  }, { projectId: draftProject.id, content: oldDraft, baseVersion: draftBase.file.version, baseContent: draftBase.content });
  assert.ok((await context.request.put(`${draftRoot}/file?path=main.tex`, { data: { content: `% DRAFT_SERVER_VERSION\n${draftBase.content}`, baseVersion: draftBase.file.version } })).ok());
  await context.addInitScript(() => {
    const open = indexedDB.open.bind(indexedDB); let delayed = false;
    indexedDB.open = function(name, version) {
      const request = version === undefined ? open(name) : open(name, version);
      if (name === 'fastwrite-offline-v1' && !delayed) {
        delayed = true;
        Object.defineProperty(request, 'onsuccess', { set(handler) { request.addEventListener('success', event => setTimeout(() => handler.call(request, event), 3500)); } });
      }
      return request;
    };
  });
  await page.goto(`${base}/projects/${draftProject.id}`); await source().waitFor();
  await source().focus(); await page.keyboard.press('Control+Home'); await page.keyboard.insertText('% NEW_INPUT\n');
  const readDraft = async path => (await (await context.request.get(`${draftRoot}/file?path=${path ?? 'main.tex'}`)).json()).content;
  await until(async () => (await readDraft()).startsWith('% NEW_INPUT\n'), 'new input saved while old draft loads');
  await page.getByRole('button', { name: 'Compare / recover (1)', exact: true }).waitFor();
  assert.ok(!(await readDraft()).includes('OLD_OFFLINE_DRAFT'));
  await page.reload(); await source().waitFor();
  await page.getByRole('button', { name: 'Compare / recover (1)', exact: true }).waitFor();
  assert.ok((await readDraft()).startsWith('% NEW_INPUT\n'));
  await page.getByRole('button', { name: 'Compare / recover (1)', exact: true }).click(); await result().waitFor();
  await until(async () => (await dialog().locator('.view-lines').allTextContents()).join('\n').includes('OLD_OFFLINE_DRAFT'), 'retained draft rendered after reload');
  await dialog().getByLabel('Recovery copy path').fill('offline-recovered.tex');
  await dialog().getByRole('button', { name: 'Save result as copy', exact: true }).click();
  await dialog().getByRole('status').filter({ hasText: 'Saved copy: offline-recovered.tex' }).waitFor();
  assert.equal(await readDraft('offline-recovered.tex'), oldDraft, 'old draft survives subsequent edits, ACK and reload');
  assert.ok((await readDraft()).startsWith('% NEW_INPUT\n'));
  await dialog().getByRole('button', { name: 'Cancel', exact: true }).click(); await dialog().waitFor({ state: 'detached' });
  const offlineProject = await create('Offline reopen regression');
  const offlineRoot = `${base}/api/projects/${offlineProject.id}`;
  await page.goto(`${base}/projects/${offlineProject.id}`); await source().waitFor();
  await context.setOffline(true);
  await source().focus(); await page.keyboard.press('Control+Home'); await page.keyboard.insertText('% OFFLINE_REOPEN\n');
  await page.locator('.save-indicator--offline').waitFor();
  await until(async () => page.evaluate(async projectId => {
    const db = await new Promise(resolve => { const request = indexedDB.open('fastwrite-offline-v1', 2); request.onsuccess = () => resolve(request.result); });
    const value = await new Promise(resolve => { const tx = db.transaction('drafts', 'readonly'); const request = tx.objectStore('drafts').get(`${projectId}:main.tex`); tx.oncomplete = () => resolve(request.result); }); db.close(); return value?.content?.includes('OFFLINE_REOPEN');
  }, offlineProject.id), 'offline draft durably committed');
  await context.route('**/file?path=main.tex', async route => { if (route.request().method() === 'PUT') await route.abort('failed'); else await route.continue(); });
  await context.setOffline(false);
  await page.reload(); await source().waitFor();
  await until(async () => (await page.locator('.source-editor > .monaco-editor-host .view-lines').allTextContents()).join('\n').includes('OFFLINE_REOPEN'), 'same-base offline draft restored after reopening');
  assert.ok(!(await (await context.request.get(`${offlineRoot}/file?path=main.tex`)).json()).content.includes('OFFLINE_REOPEN'));
  await context.unroute('**/file?path=main.tex');
  await source().focus(); await page.keyboard.press('Control+s');
  await until(async () => (await (await context.request.get(`${offlineRoot}/file?path=main.tex`)).json()).content.includes('OFFLINE_REOPEN'), 'reopened offline draft saves after retry');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: 'pass', projectId: project.id, draftProjectId: draftProject.id, cases: ['three-way references', 'versioned merge save', 'stale preview rejected', 'save recovered copy', 'late draft does not overwrite new input', 'old draft survives ACK and reload', 'offline draft durable restore and retry'] }));
} finally { await browser.close(); }
