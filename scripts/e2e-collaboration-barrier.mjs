import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const base = process.env.FASTWRITE_E2E_URL ?? 'http://127.0.0.1:3221';
const browser = await chromium.launch({ channel: process.env.FASTWRITE_E2E_CHANNEL ?? 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.stack));
const until = async (predicate, label) => { const end = Date.now() + 15000; while (!(await predicate())) { assert.ok(Date.now() < end, label); await page.waitForTimeout(40); } };
try {
  const registered = await context.request.post(`${base}/api/auth/register`, { data: { email: `barrier-${crypto.randomUUID()}@example.test`, password: 'persistence-barrier-regression', displayName: 'Barrier author' } });
  assert.ok(registered.ok(), await registered.text());
  const { token } = await registered.json();
  const headers = { authorization: `Bearer ${token}` };
  await context.addInitScript(token => { localStorage.setItem('fastwrite.session-token', token); localStorage.setItem('fastwrite.completion.enabled', 'false'); localStorage.setItem('fastwrite.collaboration.enabled', 'true'); }, token);
  const created = await context.request.post(`${base}/api/projects`, { headers, data: { name: 'Collaboration persistence barrier' } });
  assert.ok(created.ok(), await created.text());
  const project = await created.json();
  const root = `${base}/api/projects/${project.id}`;
  const read = async () => (await (await context.request.get(`${root}/file?path=main.tex`, { headers })).json()).content;
  let synced = false, hold = false;
  const delayed = [];
  await page.routeWebSocket('**/api/collaboration/socket?*', socket => {
    const server = socket.connectToServer();
    server.onMessage(message => { if (Buffer.isBuffer(message) && message[0] === 0 && message[1] === 1) synced = true; socket.send(message); });
    socket.onMessage(message => {
      if (hold && Buffer.isBuffer(message) && message[0] === 0 && message[1] === 2) delayed.push(() => server.send(message));
      else server.send(message);
    });
  });
  await page.goto(`${base}/projects/${project.id}`);
  const source = page.getByRole('textbox', { name: 'Source editor for main.tex', exact: true });
  await source.waitFor(); await until(() => synced, 'WS initial synchronization');
  hold = true;
  await source.focus(); await page.keyboard.press('Control+Home'); await page.keyboard.insertText('% BARRIER_A\n');
  await until(() => delayed.length > 0, 'WS edit intercepted');
  assert.ok(!(await read()).includes('BARRIER_A'), 'WS update has not reached the server');
  let release;
  const gate = new Promise(resolve => { release = resolve; });
  let persisted = false, requests = 0, releaseSecond;
  const secondGate = new Promise(resolve => { releaseSecond = resolve; });
  await page.route('**/collaboration/persist', async route => { const index = ++requests; if (index > 1) await secondGate; const response = await route.fetch(); if (index === 1) { persisted = true; await gate; } await route.fulfill({ response }); });
  await page.keyboard.press('Control+s');
  await until(() => persisted, 'HTTP barrier persists captured state');
  assert.ok((await read()).includes('BARRIER_A'), 'barrier overtakes the held WS frame safely');
  await source.focus(); await page.keyboard.press('Control+Home'); await page.keyboard.insertText('% BARRIER_B\n');
  release();
  await until(() => requests > 1, 'newer input enters the next persistence request');
  assert.equal(await page.locator('.save-indicator--saved').count(), 0, 'old ACK cannot mark newer input saved');
  assert.match((await page.locator('.source-editor .view-lines').allTextContents()).join('\n'), /BARRIER_B/);
  assert.ok(!(await read()).includes('BARRIER_B'), 'ACK only covers the captured revision');
  releaseSecond();
  await until(async () => (await read()).includes('BARRIER_B'), 'second flush persists newer input');
  const expected = await read();
  hold = false;
  for (const send of delayed) send();
  await page.waitForTimeout(1400);
  assert.equal(await read(), expected, 'delayed WS duplicates do not duplicate text');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: 'pass', projectId: project.id, cases: ['HTTP barrier before WS delivery', 'old ACK preserves newer input', 'second flush includes newer input', 'late WS delivery is idempotent'] }));
} finally { await browser.close(); }
