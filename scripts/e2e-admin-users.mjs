import { expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { startTestServer, launchTestBrowser } from './fixtures/browser-test.mjs';

const output = fileURLToPath(new URL('../output/ui-admin-users', import.meta.url));
await mkdir(output, { recursive: true });
const setup = await startTestServer();
const browser = await launchTestBrowser();
const errors = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 960 }, reducedMotion: 'reduce', serviceWorkers: 'block' });
  const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
  const admin = await (await context.request.post(`${setup.origin}/api/auth/login`, { data: { email: 'e2e-admin@example.test', password: 'fastwrite-e2e-only-password' } })).json();
  await context.addInitScript(token => { localStorage.setItem('fastwrite.session-token', token); localStorage.setItem('fastwrite.theme', 'light'); }, admin.token);
  const teamResponse = await context.request.post(`${setup.origin}/api/teams`, { headers: { authorization: `Bearer ${admin.token}` }, data: { name: '研究团队' } });
  assert.equal(teamResponse.status(), 201);
  await page.goto(`${setup.origin}/panel`);
  await page.getByRole('navigation', { name: '项目来源' }).getByRole('button', { name: '用户管理', exact: true }).click();
  await expect(page.getByRole('heading', { name: '用户管理', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '新增用户', exact: true }).click();
  let dialog = page.getByRole('dialog', { name: '新增用户', exact: true });
  await dialog.getByRole('textbox', { name: '名称', exact: true }).fill('浏览器测试用户');
  await dialog.getByRole('textbox', { name: '邮箱', exact: true }).fill('browser-member@example.test');
  await dialog.getByLabel('初始密码（至少 12 个字符）').fill('browser-member-test-password');
  await dialog.getByRole('textbox', { name: '操作原因（至少 8 个字符）' }).fill('浏览器验证新增用户操作');
  await dialog.getByRole('button', { name: '保存', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  let row = page.getByRole('table', { name: '用户列表' }).getByRole('row').filter({ hasText: 'browser-member@example.test' });
  await expect(row).toContainText('浏览器测试用户');
  await row.getByRole('button', { name: '编辑 浏览器测试用户', exact: true }).click();
  dialog = page.getByRole('dialog', { name: '编辑用户', exact: true });
  await dialog.getByRole('textbox', { name: '名称', exact: true }).fill('修改后的用户');
  await dialog.getByRole('textbox', { name: '操作原因（至少 8 个字符）' }).fill('浏览器验证编辑用户操作');
  await dialog.getByRole('button', { name: '保存', exact: true }).click();
  await expect(dialog).toHaveCount(0); await expect(row).toContainText('修改后的用户');
  await row.getByRole('button', { name: '团队管理 修改后的用户', exact: true }).click();
  dialog = page.getByRole('dialog', { name: '用户团队管理' });
  await dialog.getByRole('textbox', { name: '操作原因（至少 8 个字符）' }).fill('浏览器验证添加团队成员');
  await dialog.getByRole('combobox', { name: '研究团队 成员角色' }).click();
  await page.getByRole('option', { name: '成员', exact: true }).click();
  await expect(dialog.getByRole('combobox', { name: '研究团队 成员角色' })).toContainText('成员');
  await expect(dialog.getByRole('combobox', { name: '研究团队 成员角色' })).toBeEnabled();
  await dialog.getByRole('button', { name: '完成', exact: true }).click();
  await page.screenshot({ path: join(output, 'users-light-1440.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: '新增用户', exact: true })).toBeVisible();
  await page.screenshot({ path: join(output, 'users-mobile-390.png') });
  await page.setViewportSize({ width: 1440, height: 960 });
  // Ordinary members never see the administration navigation.
  const member = await (await context.request.post(`${setup.origin}/api/auth/login`, { data: { email: 'browser-member@example.test', password: 'browser-member-test-password' } })).json();
  const memberContext = await browser.newContext({ serviceWorkers: 'block' });
  await memberContext.addInitScript(token => localStorage.setItem('fastwrite.session-token', token), member.token);
  const memberPage = await memberContext.newPage(); await memberPage.goto(`${setup.origin}/panel`);
  await expect(memberPage.getByRole('button', { name: '团队与协作', exact: true })).toBeVisible();
  await expect(memberPage.getByRole('button', { name: '用户管理', exact: true })).toHaveCount(0);
  await memberContext.close();
  await row.getByRole('button', { name: '删除 修改后的用户', exact: true }).click();
  dialog = page.getByRole('dialog', { name: '删除用户', exact: true });
  await dialog.getByRole('textbox', { name: '操作原因（至少 8 个字符）' }).fill('浏览器验证删除测试用户');
  await dialog.getByRole('button', { name: '确认删除', exact: true }).click();
  await expect(dialog).toHaveCount(0); await expect(row).toHaveCount(0);
  // The provider itself is external; verify the profile form using its API contract.
  const signupContext = await browser.newContext({ viewport: { width: 1024, height: 800 }, serviceWorkers: 'block' });
  await signupContext.route('**/api/auth/fastcas/signup', route => route.request().method() === 'GET'
    ? route.fulfill({ json: { email: 'cas-user@example.test', displayName: 'FastCAS 用户' } })
    : route.fulfill({ status: 409, json: { code: 'account_exists', error: { code: 'account_exists', message: '此邮箱已有 FastWrite 账号，请登录后绑定' } } }));
  const signupPage = await signupContext.newPage(); signupPage.on('pageerror', error => errors.push(error.message));
  await signupPage.goto(`${setup.origin}/panel?fastcas=register`);
  dialog = signupPage.getByRole('dialog', { name: '注册并绑定 FastWrite 账号' });
  await expect(dialog.getByRole('textbox', { name: 'FastWrite 登录邮箱' })).toHaveValue('cas-user@example.test');
  await dialog.getByLabel('密码（至少 12 个字符）', { exact: true }).fill('fastcas-user-test-password');
  await dialog.getByLabel('确认密码', { exact: true }).fill('fastcas-user-test-password');
  await expect(dialog.getByRole('button', { name: '注册并绑定', exact: true })).toBeEnabled();
  await signupPage.screenshot({ path: join(output, 'fastcas-register.png') });
  const submission = signupPage.waitForRequest(request => request.url().endsWith('/api/auth/fastcas/signup') && request.method() === 'POST');
  await dialog.getByRole('button', { name: '注册并绑定', exact: true }).click();
  assert.deepEqual((await submission).postDataJSON(), { email: 'cas-user@example.test', displayName: 'FastCAS 用户', password: 'fastcas-user-test-password' });
  await expect(dialog.getByRole('alert')).toBeVisible();
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
  await expect(signupPage).toHaveURL(`${setup.origin}/panel`);
  await signupPage.getByRole('button', { name: /登录/ }).first().click();
  await expect(signupPage.getByRole('dialog', { name: '登录', exact: true })).toBeVisible();
  await expect(signupPage.getByRole('button', { name: '创建账号', exact: true })).toHaveCount(0);
  await signupContext.close();
  assert.deepEqual(errors, []); console.log(JSON.stringify({ status: 'passed', output }));
} finally { await browser.close(); await setup.close(); }
