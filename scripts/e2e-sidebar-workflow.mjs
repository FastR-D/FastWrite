import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const data = await mkdtemp(join(tmpdir(), 'fastwrite-sidebar-browser-'));
const server = spawn('bun', ['scripts/e2e-reference-fixture.ts'], { cwd: root, env: { ...process.env, FASTWRITE_DATA_DIR: data, FASTWRITE_PORT: '0', FASTWRITE_WEB_DIR: join(root, 'apps/web/dist') }, stdio: ['ignore', 'pipe', 'pipe'] });
let logs = '', browser;
server.stderr.on('data', chunk => { logs += chunk; });
try {
  const base = await new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error(`Fixture timeout: ${logs}`)), 20000);
    server.stdout.on('data', chunk => { logs += chunk; const match = logs.match(/REFERENCE_E2E_URL=(http:\/\/\S+)/); if (match) { clearTimeout(timer); resolve(match[1]); } });
    server.on('exit', code => { clearTimeout(timer); reject(new Error(`Fixture exited ${code}: ${logs}`)); });
  });
  browser = await chromium.launch({ channel: process.env.FASTWRITE_E2E_CHANNEL ?? 'chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 1600, height: 1000 } });
  await context.addInitScript(() => { localStorage.setItem('fastwrite.completion.enabled', 'false'); });
  await context.route('**/api/projects/*/compile', route => route.fulfill({ status: 503, json: { error: { code: 'fixture_compile_disabled', message: 'No compile in this workflow test.' } } }));
  const page = await context.newPage(), errors = []; page.on('pageerror', error => errors.push(error.message));
  const project = await (await context.request.post(`${base}/api/projects`, { data: { name: 'Sidebar workflow acceptance' } })).json();
  const api = `${base}/api/projects/${project.id}`;
  const file = await (await context.request.get(`${api}/file?path=main.tex`)).json();
  const content = `\\documentclass{article}\n\\begin{document}\n\\section{Results}\nOur method improves accuracy by 12% for ${'LongUnbrokenEvidenceString'.repeat(20)}.\n\\end{document}\n`;
  assert.ok((await context.request.put(`${api}/file?path=main.tex`, { data: { baseVersion: file.file.version, content } })).ok());
  assert.ok((await context.request.post(`${api}/claim-scans`)).ok());
  await page.goto(`${base}/projects/${project.id}`);
  const editor = page.getByRole('textbox', { name: '源文件编辑器： main.tex', exact: true }); await editor.waitFor();
  const nav = page.getByRole('navigation', { name: '工作区视图' });
  const sidebar = page.locator('.workspace-sidebar');
  const choose = async label => { const button = nav.getByRole('button', { name: label, exact: true }); if (await button.getAttribute('aria-pressed') !== 'true') await button.click(); };
  const divider = page.getByRole('separator', { name: '调整文件面板大小', exact: true });
  await divider.focus(); await divider.press('ArrowRight'); await divider.press('ArrowRight');
  const width = (await sidebar.boundingBox()).width;
  for (let round = 0; round < 2; round++) for (const label of ['证据', '大纲', '参考论文', 'Skill', '协作', 'Git', '文件']) { await choose(label); assert.equal((await sidebar.boundingBox()).width, width, `stable sidebar width for ${label}`); }
  await page.keyboard.press('Control+b'); await expect(sidebar).toBeHidden();
  await page.reload(); await editor.waitFor(); await expect(sidebar).toBeHidden();
  await choose('Skill'); assert.equal((await sidebar.boundingBox()).width, width, 'collapsed width survives reload');
  await choose('协作');
  await expect(page.locator('#sidebar-collaboration').getByRole('combobox', { name: '写作模式', exact: true })).toBeVisible();
  await expect(page.locator('.source-editor .editor-mode-bar')).toHaveCount(0);
  await choose('证据');
  const evidence = page.locator('#sidebar-evidence'); await evidence.locator('.claim-ledger-item').first().waitFor();
  assert.ok(await evidence.evaluate(element => element.scrollWidth <= element.clientWidth + 1), 'long evidence does not overflow');
  assert.ok(await evidence.locator('.claim-ledger-item').first().evaluate(element => element.scrollWidth <= element.clientWidth + 1), 'claim text wraps inside its row');
  await editor.focus(); await editor.press('Control+Home'); await editor.press('ArrowDown'); await editor.press('ArrowDown'); await editor.press('ArrowDown');
  const targets = page.locator('.revise-chat__targets');
  await targets.getByRole('button', { name: '使用当前段落', exact: true }).waitFor();
  const paragraph = await targets.getByRole('button', { name: '使用当前段落', exact: true }).boundingBox();
  const section = await targets.getByRole('button', { name: '使用当前章节', exact: true }).boundingBox();
  assert.equal(paragraph.y, section.y, 'paragraph and section actions share one row');
  assert.ok((await page.locator('.ai-workspace__header').boundingBox()).height <= 38, 'compact AI header');
  assert.ok((await page.locator('.revise-chat__messages').boundingBox()).height < 130, 'compact empty revise messages');
  await expect(page.getByText('每轮回复都会优化当前候选内容，接受后才会修改文件。', { exact: true })).toHaveCount(0);
  await choose('Skill'); const skills = page.locator('#sidebar-skills');
  for (let index = 0; index < 6; index++) await skills.getByRole('checkbox').nth(index).check();
  await expect(skills.locator('input:checked')).toHaveCount(6);
  const header = skills.locator('header');
  await expect(header.getByRole('button', { name: '确定', exact: true })).toBeVisible(); await expect(header.getByRole('button', { name: '清空选择', exact: true })).toBeVisible();
  const sourceBefore = await page.locator('.monaco-editor-host').getAttribute('data-model-id');
  await skills.getByRole('button', { name: /^查看 .* 详情$/ }).first().click();
  const detailPanel = page.getByRole('tabpanel', { name: /^Skill ·/ }); await expect(detailPanel.getByLabel('Skill 具体内容')).not.toBeEmpty();
  await mkdir(join(root, 'output/sidebar-workflow'), { recursive: true });
  await page.screenshot({ path: join(root, 'output/sidebar-workflow/skill-detail.png') });
  await page.getByRole('button', { name: /^关闭 Skill ·/ }).click(); await expect(editor).toBeVisible();
  assert.equal(await page.locator('.monaco-editor-host').getAttribute('data-model-id'), sourceBefore, 'reading Skill does not replace source buffer');
  await header.getByRole('button', { name: '清空选择', exact: true }).click(); await expect(skills.locator('input:checked')).toHaveCount(0);
  await choose('参考论文'); const references = page.locator('#sidebar-reference-style');
  const dialog = page.getByRole('dialog', { name: '添加参考论文', exact: true });
  await references.getByRole('button', { name: '添加参考论文', exact: true }).click();
  await dialog.getByRole('button', { name: 'LaTeX 源码', exact: true }).click();
  await dialog.getByLabel('论文标题（可选）', { exact: true }).fill('Pasted LaTeX');
  await dialog.getByRole('textbox', { name: 'LaTeX 论文源码', exact: true }).fill('\\documentclass{article}\n\\begin{document}\n\\section{Introduction}\nPasted reference prose.\n\\end{document}');
  await dialog.getByRole('button', { name: '导入论文', exact: true }).click(); await expect(dialog).toBeHidden();
  await references.getByRole('button', { name: '启用并保存参考范围', exact: true }).waitFor();
  for (const value of ['10.1234/example', 'arxiv:2301.12345v2', 'https://papers.example.test/direct.pdf']) {
    await references.getByRole('button', { name: '添加参考论文', exact: true }).click();
    await dialog.getByRole('button', { name: 'DOI / arXiv / 链接', exact: true }).click();
    await dialog.getByRole('textbox', { name: '论文标识或链接', exact: true }).fill(value);
    await dialog.getByRole('button', { name: '导入论文', exact: true }).click(); await expect(dialog).toBeHidden();
  }
  const calls = await (await context.request.get(`${base}/__reference_e2e__/calls`)).json();
  assert.ok(calls.some(call => call.operation === 'reference-download' && call.input.url.includes('api.crossref.org/works/')));
  assert.ok(calls.some(call => call.operation === 'reference-download' && call.input.url === 'https://arxiv.org/pdf/2301.12345v2'));
  await references.getByRole('button', { name: '添加参考论文', exact: true }).click();
  await dialog.getByRole('textbox', { name: '论文标识或链接', exact: true }).fill('not an identifier');
  await dialog.getByRole('button', { name: '导入论文', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('请输入');
  await page.screenshot({ path: join(root, 'output/sidebar-workflow/reference-import.png') });
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
  await page.locator('.ai-workspace').getByRole('button', { name: '智能助手', exact: true }).click();
  await expect(page.getByRole('region', { name: '智能助手工作区' }).getByText('任务技能', { exact: true })).toHaveCount(0);
  assert.equal((await (await context.request.get(`${api}/file?path=main.tex`)).json()).content, content, 'UI and imports preserve manuscript');
  // A failed request appears once in the notification center, never as raw panel text.
  await context.route('**/api/agent-skills', route => route.abort('failed'));
  await choose('Skill'); await skills.getByRole('button', { name: '刷新 Skill', exact: true }).click();
  const notification = page.getByRole('complementary', { name: '工作区通知', exact: true });
  await expect(notification.getByRole('alert')).toHaveCount(1);
  await expect(notification).toContainText('无法连接到服务器');
  await expect(page.getByText('Failed to fetch', { exact: true })).toHaveCount(0);
  const box = await notification.boundingBox(); assert.ok(box.x > 1000 && box.y > 650, 'notification sits at the bottom right');
  await page.screenshot({ path: join(root, 'output/sidebar-workflow/network-notification.png') });
  await notification.getByRole('button', { name: '关闭通知', exact: true }).click();
  await expect(notification.getByRole('alert')).toHaveCount(0);
  assert.deepEqual(errors, []);
  console.log('PASS: stable sidebar width across all tabs and reload; long evidence wrapping; compact AI layout; unlimited Skills and central detail tab; PDF/LaTeX/DOI/arXiv import and validation');
} finally {
  await browser?.close();
  if (server.exitCode === null) { const exited = new Promise(resolve => server.once('exit', resolve)); server.kill('SIGTERM'); await exited; }
  await rm(data, { recursive: true, force: true });
}
